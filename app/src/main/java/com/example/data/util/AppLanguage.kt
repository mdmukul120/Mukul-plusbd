    companion object {
        fun fromCode(code: String): AppLanguage {
            return entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: BENGALI
        }
    }
}

object LanguageManager {
    var currentLanguage by mutableStateOf(AppLanguage.BENGALI)
        private set

    fun init(context: Context) {
        val prefs = context.getSharedPreferences("app_settings", Context.MODE_PRIVATE)
        val code = prefs.getString("selected_language", AppLanguage.BENGALI.code) ?: AppLanguage.BENGALI.code
        currentLanguage = AppLanguage.fromCode(code)
    }

    fun setLanguage(context: Context, language: AppLanguage) {
        currentLanguage = language
        val prefs = context.getSharedPreferences("app_settings", Context.MODE_PRIVATE)
        prefs.edit().putString("selected_language", language.code).apply()
    }

    // Helper translation string retrieval
    fun get(key: String): String {
        val langMap = translations[currentLanguage] ?: translations[AppLanguage.ENGLISH] ?: emptyMap()
        return langMap[key] ?: translations[AppLanguage.ENGLISH]?.get(key) ?: key
    }

